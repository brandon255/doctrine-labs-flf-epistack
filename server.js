/**
 * Load + run the Epistack engine on one AISI company's evidence blocks.
 * Mirrors scripts/aisi-run.js from the sibling aisi-lineage-toolkit repo:
 * reads the source registry, hydrates provenance.context as a URL string,
 * and indexes the registry by every key the engine might look up.
 *
 * @returns { id, block_count, has_registry, summary, correlated_documents, lineages }
 *          or { error } for not-found / read failures.
 */
function loadAisiCompany(id) {
  const dir = join(AISI_DIR, id);
  if (!existsSync(dir)) return { error: "not found" };
  const blocksFile = join(dir, "evidence_blocks.json");
  const registryFile = join(dir, "source_registry.json");
  if (!existsSync(blocksFile)) return { error: "not found" };
  try {
    const blocksRaw = JSON.parse(readFileSync(blocksFile, "utf8"));
    const blocksArray = Array.isArray(blocksRaw) ? blocksRaw : (blocksRaw.blocks ?? []);

    let registryForEngine = {};
    let lineages = {};
    const hasRegistry = existsSync(registryFile);
    if (hasRegistry) {
      const registry = JSON.parse(readFileSync(registryFile, "utf8"));
      lineages = registry.lineages ?? {};
      for (const [docId, entry] of Object.entries(registry.documents ?? {})) {
        if (!entry || typeof entry !== "object") continue;
        registryForEngine[docId] = entry;
        if (entry.url) registryForEngine[entry.url] = entry;
        if (entry.document_id) {
          registryForEngine[entry.document_id] = entry;
          const baseId = entry.document_id.split(/[-_]/).slice(0, 2).join("-");
          if (baseId !== entry.document_id) registryForEngine[baseId] = entry;
        }
      }
    }

    // Hydrate: ensure every block has provenance.context as a URL string,
    // falling back through source.url → source.identifier → registry lookup.
    const hydratedBlocks = blocksArray.map((block) => {
      const copy = JSON.parse(JSON.stringify(block));
      if (!copy.provenance) copy.provenance = {};
      let url = copy.source?.url;
      if (!url && copy.source?.identifier && registryForEngine[copy.source.identifier]?.url) {
        url = registryForEngine[copy.source.identifier].url;
      }
      const ctx = copy.provenance.context;
      if (typeof ctx === "string") {
        if (url && !ctx.includes(url)) copy.provenance.context = url;
      } else if (ctx && typeof ctx === "object" && ctx.url) {
        copy.provenance.context = ctx.url;
      } else if (url) {
        copy.provenance.context = url;
      }
      return copy;
    });

    const genealogy = resolveGenealogy(hydratedBlocks, { registry: registryForEngine });
    const summary = summarise(genealogy, blocksArray.length);
    const correlated_documents = (genealogy.documentClusters ?? []).filter((c) => c.block_count > 1);
    return {
      id,
      block_count: blocksArray.length,
      has_registry: hasRegistry,
      summary,
      correlated_documents,
      lineages,
    };
  } catch (e) {
    return { error: e.message };
  }
}

function readSubquestion(caseDir) {
  try {
    const p = join(caseDir, "SUBQUESTION.md");
    if (!existsSync(p)) return null;
    return readFileSync(p, "utf8").trim();
  } catch {
    return null;
  }
}

/**
 * Read the request body as a raw Buffer (for PDF upload).
 * Caps at 25 MB to keep memory bounded on the Render free tier.
 */
function readRawBody(req, maxBytes = 25 * 1024 * 1024) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let total = 0;
    req.on("data", (chunk) => {
      total += chunk.length;
      if (total > maxBytes) {
        req.destroy();
        reject(new Error(`request body exceeds ${maxBytes} bytes`));
        return;
      }
      chunks.push(chunk);
    });
    req.on("end", () => resolve(Buffer.concat(chunks, total)));
    req.on("error", reject);
  });
}

/**
 * Parse a multipart/form-data body and return the first file part.
 * Tiny purpose-built parser — no dependencies. Looks for a part with a
 * filename; returns { filename, contentType, bytes } or null.
 */
function parseMultipartForFile(buffer, boundary) {
  const sep = Buffer.from(`--${boundary}`);
  const parts = [];
  let start = 0;
  while (start < buffer.length) {
    const idx = buffer.indexOf(sep, start);
    if (idx === -1) break;
    const next = buffer.indexOf(sep, idx + sep.length);
    const slice = next === -1 ? buffer.slice(idx + sep.length) : buffer.slice(idx + sep.length, next);
    parts.push(slice);
    if (next === -1) break;
    start = next;
  }
  for (const part of parts) {
    const headerEnd = part.indexOf("\r\n\r\n");
    if (headerEnd === -1) continue;
    const headerText = part.slice(0, headerEnd).toString("utf8");
    if (!/filename=/i.test(headerText)) continue;
    const filenameMatch = headerText.match(/filename="?([^";\r\n]+)"?/i);
    const ctMatch = headerText.match(/content-type:\s*([^\r\n]+)/i);
    // Strip the trailing \r\n before the next boundary.
    let body = part.slice(headerEnd + 4);
    if (body.length >= 2 && body[body.length - 2] === 0x0d && body[body.length - 1] === 0x0a) {
      body = body.slice(0, -2);
    }
    return {
      filename: filenameMatch?.[1] ?? "uploaded.bin",
      contentType: ctMatch?.[1]?.trim() ?? "application/octet-stream",
      bytes: body,
    };
  }
  return null;
}

async function handle(req, res) {
  try {
    const url = new URL(req.url, `http://${HOST}`);
    const ctype = String(req.headers["content-type"] ?? "").toLowerCase();

    // ----- PDF or multipart: handle here, never as parsed JSON. -----
    if (req.method === "POST" && url.pathname === "/api/analyze") {
      if (ctype.startsWith("multipart/form-data")) {
        const m = ctype.match(/boundary=(?:"([^"]+)"|([^;]+))/i);
        const boundary = m?.[1] ?? m?.[2];
        if (!boundary) {
          res.writeHead(400, { "content-type": "application/json" });
          res.end(JSON.stringify({ ok: false, error: "multipart boundary missing" }));
          return;
        }
        const raw = await readRawBody(req);
        const file = parseMultipartForFile(raw, boundary);
        if (!file) {
          res.writeHead(400, { "content-type": "application/json" });
          res.end(JSON.stringify({ ok: false, error: "no file part in multipart body" }));
          return;
        }
        await handleAnalyze(res, file.bytes, file.filename, file.contentType);
        return;
      }
      if (ctype === "application/pdf") {
        const bytes = await readRawBody(req);
        await handleAnalyze(res, bytes, "uploaded.pdf", "application/pdf");
        return;
      }
      // else fall through to JSON parsing.
    }

    const body = ["POST", "PUT", "PATCH"].includes(req.method) ? await readBody(req) : {};
    const result = await routeRequest({
      method: req.method,
      pathname: url.pathname,
      search: url.searchParams,
      body,
    });
    res.writeHead(result.status, result.headers);
    res.end(result.body);
  } catch (e) {
    res.writeHead(500, { "content-type": "application/json" });
    res.end(JSON.stringify({ ok: false, error: e.message }));
  }
}

async function handleAnalyze(res, bytes, filename, contentType) {
  let parsed;
  if (contentType === "application/pdf" || filename.toLowerCase().endsWith(".pdf")) {
    parsed = await parsePdfEvidence(bytes, filename);
  } else if (contentType.startsWith("text/markdown") || filename.toLowerCase().endsWith(".md")) {
    parsed = parseMarkdownEvidence(bytes.toString("utf8"));
  } else if (contentType.startsWith("application/json") || filename.toLowerCase().endsWith(".json")) {
    parsed = parseJsonEvidence(bytes.toString("utf8"));
  } else {
    // Fall back: try JSON first, then markdown.
    const text = bytes.toString("utf8");
    const trimmed = text.trim();
    if (trimmed.startsWith("{") || trimmed.startsWith("[")) {
      parsed = parseJsonEvidence(text);
    } else {
      parsed = parseMarkdownEvidence(text);
    }
  }
  if (!parsed.ok) {
    res.writeHead(400, { "content-type": "application/json" });
    res.end(JSON.stringify({ ok: false, error: parsed.error, hint: parsed.hint ?? null }));
    return;
  }
  try {
    const genealogy = resolveGenealogy(parsed.blocks, { aliases: {}, registry: {} });
    const summary = summarise(genealogy, parsed.blocks.length);
    const source = contentType === "application/pdf" || filename.toLowerCase().endsWith(".pdf")
      ? "pdf"
      : filename.toLowerCase().endsWith(".md") || contentType.startsWith("text/markdown")
      ? "md"
      : "json";
    res.writeHead(200, { "content-type": "application/json; charset=utf-8" });
    res.end(
      JSON.stringify({
        ok: true,
        source,
        filename,
        block_count: parsed.blocks.length,
        summary,
        assessment_line: summary.assessment_line,
        text_excerpt: parsed.text_excerpt ?? null,
      })
    );
  } catch (e) {
    res.writeHead(500, { "content-type": "application/json" });
    res.end(JSON.stringify({ ok: false, error: e.message }));
  }
}

